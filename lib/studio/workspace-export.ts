/**
 * Per-revision documents of the workspace export. Deliberately free of server-only imports so it can be tested with
 * stand-ins: the export never renders a PDF. It copies PDFs that are already registered, renders HTML read-only from the
 * pinned (or standard) layout, and tells the reader in README.txt which revisions still have no PDF.
 */
export type ExportRevision = {
  id: string;
  number: string;
  revisionNumber: number;
};
export type ExportFile = { name: string; content: string | Uint8Array };
export type ExportDeps = {
  /** Read-only HTML for the revision (never pins a layout). */
  html(revision: ExportRevision): Promise<{ filename: string; html: string }>;
  /** The already registered, digest-verified PDF, or null. Must never render or generate one. */
  registeredPdf(
    revision: ExportRevision,
  ): Promise<{ filename: string; bytes: Uint8Array } | null>;
};
export const EXPORT_CONCURRENCY = 4;

export async function collectRevisionFiles(
  revisions: readonly ExportRevision[],
  deps: ExportDeps,
  concurrency = EXPORT_CONCURRENCY,
) {
  const files: ExportFile[] = [],
    missingPdf: ExportRevision[] = [];
  for (let at = 0; at < revisions.length; at += concurrency) {
    const batch = revisions.slice(at, at + concurrency);
    // Concurrency only overlaps reads; results are appended in revision order so the archive is deterministic.
    const results = await Promise.all(
      batch.map(async (revision) => ({
        revision,
        html: await deps.html(revision),
        pdf: await deps.registeredPdf(revision),
      })),
    );
    for (const { revision, html, pdf } of results) {
      files.push({ name: `quotes/${html.filename}`, content: html.html });
      if (pdf)
        files.push({ name: `quotes/${pdf.filename}`, content: pdf.bytes });
      else missingPdf.push(revision);
    }
  }
  return { files, missingPdf };
}

export function workspaceReadme(input: {
  organization: string;
  generatedAt: string;
  missingPdf: readonly ExportRevision[];
}) {
  const lines = [
    "Trace workspace export",
    `Organization: ${input.organization}`,
    `Generated: ${input.generatedAt}`,
    "Generated by Trace",
    "",
    "Issued sealed revisions include self-contained HTML, and the PDF when one has already been generated. Drafts appear only in data/quotes.csv.",
    "The export never generates PDFs and never pins layouts: a revision that has not been opened for print yet is exported in the standard layout.",
    "CSV fields exclude internal costs and approval data. Templates include active saved layouts and the current brand.",
    "Records are read in pages; this ZIP is not a transactional database backup.",
  ];
  if (input.missingPdf.length) {
    lines.push(
      "",
      `${input.missingPdf.length} issued revision(s) have no PDF yet:`,
    );
    for (const revision of input.missingPdf)
      lines.push(
        `PDF not generated yet: open the quotation and use Download PDF, then export again. ${revision.number} revision ${revision.revisionNumber}`,
      );
  }
  return lines.join("\n") + "\n";
}
